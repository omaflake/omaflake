import Foundation

/// What of the host's clipboard a guest may see, and what a guest may put there (spec §11.9; `ClipboardBridge` in
/// omaf-runner asks before it sends or writes anything).
public enum ClipboardPolicy {
    public static let text = "text/plain;charset=utf-8"
    public static let png = "image/png"

    /// Marker types of the nspasteboard.org convention: content that is a secret (password managers), that is there
    /// only for a moment, or that an app put there by itself – none of it is the user copying something for the guest
    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    /// Whether a pasteboard content with these types (`NSPasteboard.types`, raw values) may go to a guest
    public static func shares(types: [String]) -> Bool {
        !types.contains { privateTypes.contains($0) }
    }

    /// Whether a guest's content of this MIME type is put on the host's clipboard (anything else is ignored whole:
    /// the clipboard stays as it is)
    public static func accepts(mime: String) -> Bool {
        mime == text || mime == png
    }
}
