"""Generates omaflake's design tokens from brand/tokens.toml (plan B119):

    Sources/OmaflakeApp/BrandTokens.swift   SwiftUI (Color, CGFloat, Font)
    crates/omaflake-brand/src/tokens.rs     Rust, no dependencies (colours as [u8; 4] and [f32; 4], lengths as f32)
    brand/omaflake-look.toml                the guests' omaflake look ([look]) as look data (schema look/v1) – copied
                                            into omaflake/catalog as looks/omaflake/omaflake/look.toml

Needs Python 3.11+ (tomllib), nothing else. Run from anywhere:
    python3 tokens.py            write the generated files
    python3 tokens.py --check    fail (exit 1) when a generated file is out of date
generate.py runs it as well and takes the palette from here.
"""
import os, sys, tomllib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SOURCE = os.path.join(HERE, "tokens.toml")
SWIFT = os.path.join(ROOT, "Sources", "OmaflakeApp", "BrandTokens.swift")
RUST = os.path.join(ROOT, "crates", "omaflake-brand", "src", "tokens.rs")
NIX = os.path.join(HERE, "omaflake-look.toml")

WEIGHTS = ("regular", "medium", "semibold", "bold", "heavy")
LENGTH_GROUPS = ("spacing", "radius", "glow", "size", "icon")


def load():
    with open(SOURCE, "rb") as f:
        return tomllib.load(f)


def palette():
    """The brand palette as {name: "#RRGGBB"} – generate.py draws the artwork with it."""
    return dict(load()["palette"])


def hex_rgb(value):
    v = value.lstrip("#")
    if len(v) != 6:
        raise ValueError(f"colour {value!r}: expected #RRGGBB")
    return [int(v[i:i + 2], 16) / 255 for i in (0, 2, 4)]


def resolve(tokens, name, spec):
    """A semantic colour as (r, g, b, a) floats 0…1."""
    keys = [k for k in ("palette", "hex", "rgb") if k in spec]
    if len(keys) != 1:
        raise ValueError(f"color.{name}: give exactly one of palette, hex, rgb")
    if "palette" in spec:
        rgb = hex_rgb(tokens["palette"][spec["palette"]])
    elif "hex" in spec:
        rgb = hex_rgb(spec["hex"])
    else:
        rgb = [float(x) for x in spec["rgb"]]
    return (*rgb, float(spec.get("alpha", 1.0)))


def camel(name):
    head, *rest = name.split("_")
    return head + "".join(p[:1].upper() + p[1:] for p in rest)


def num(x):
    """A short decimal literal valid in Swift and Rust (always with a fractional part)."""
    s = f"{float(x):.6f}".rstrip("0")
    return s + "0" if s.endswith(".") else s


def check_weight(where, weight):
    if weight not in WEIGHTS:
        raise ValueError(f"{where}: weight {weight!r} is not one of {', '.join(WEIGHTS)}")
    return weight


HEADER = "SPDX-License-Identifier: AGPL-3.0-or-later\n{c} Generated by brand/tokens.py from brand/tokens.toml – do not edit.\n"


# --- Swift ------------------------------------------------------------------------------------------------------------

def swift(t):
    out = ["// " + HEADER.format(c="//"), "import SwiftUI\n\n",
           "/// omaflake's design tokens (brand/tokens.toml); `BrandStyle` and the views use these.\n",
           "enum BrandTokens {\n"]

    def group(name, doc, lines):
        out.append(f"    /// {doc}\n    enum {name} {{\n")
        out.extend(f"        {line}\n" for line in lines)
        out.append("    }\n\n")

    group("Palette", "Brand palette", [
        f"static let {camel(k)} = Color(red: {int(v[1:3], 16)} / 255, green: {int(v[3:5], 16)} / 255, "
        f"blue: {int(v[5:7], 16)} / 255) // {v.upper()}" for k, v in t["palette"].items()])

    colors = []
    for k, spec in t["color"].items():
        resolve(t, k, spec)  # validates
        alpha = spec.get("alpha")
        if "system" in spec:
            colors.append(f"static let {camel(k)} = Color.{spec['system']}")
            continue
        if "palette" in spec:
            base = f"Palette.{camel(spec['palette'])}"
        elif "hex" in spec:
            r, g, b = hex_rgb(spec["hex"])
            base = f"Color(red: {num(r)}, green: {num(g)}, blue: {num(b)})"
        else:
            r, g, b = spec["rgb"]
            base = f"Color(red: {num(r)}, green: {num(g)}, blue: {num(b)})"
        colors.append(f"static let {camel(k)} = {base}" + (f".opacity({num(alpha)})" if alpha is not None else ""))
    group("Colors", "Semantic colours (system ones stay SwiftUI's own colour)", colors)

    group("Opacity", "Opacities applied to another colour",
          [f"static let {camel(k)}: Double = {num(v)}" for k, v in t["opacity"].items()])
    for g in LENGTH_GROUPS:
        group(camel(g)[:1].upper() + camel(g)[1:], f"[{g}] in points",
              [f"static let {camel(k)}: CGFloat = {num(v)}" for k, v in t[g].items()])

    group("FontFamily", "Font families (on macOS the system fonts)",
          [f'static let {camel(k)} = "{v}"' for k, v in t["font"].items()])
    fonts = []
    for k, s in t["font_style"].items():
        weight = check_weight(f"font_style.{k}", s["weight"])
        design = s.get("design", "default")
        fonts.append(f"static let {camel(k)} = Font.system(size: {num(s['size'])}, weight: .{weight}"
                     + (f", design: .{design})" if design != "default" else ")"))
    group("Fonts", "Named fonts", fonts)
    texts = []
    for k, s in t["text"].items():
        check_weight(f"text.{k}", s["weight"])
        texts.append(f"static let {camel(k)}: Font = .{camel(k)} // {num(s['size'])} pt {s['weight']} elsewhere")
    group("TextStyle", "System text styles (sizes in tokens.toml for the other interfaces)", texts)

    out[-1] = out[-1].rstrip("\n") + "\n"
    out.append("}\n")
    return "".join(out)


# --- Rust -------------------------------------------------------------------------------------------------------------

def rust(t):
    out = ["// " + HEADER.format(c="//"), "\n",
           "use crate::Token;\n\n"]
    entries = []

    def color_const(rgba):
        b = ", ".join(str(round(x * 255)) for x in rgba)
        f = ", ".join(num(x) for x in rgba)
        return f"Color {{ rgba8: [{b}], rgba: [{f}] }}"

    def module(name, doc, lines):
        out.append(f"/// {doc}\npub mod {name} {{\n")
        if any("Color" in line for line in lines):
            out.append("    use crate::Color;\n")
        if any("FontStyle" in line for line in lines):
            out.append("    use crate::{FontStyle, Weight};\n")
        out.extend(f"    {line}\n" for line in lines)
        out.append("}\n\n")

    lines = []
    for k, v in t["palette"].items():
        rgba = (*hex_rgb(v), 1.0)
        lines.append(f"/// {v.upper()}\n    pub const {k.upper()}: Color = {color_const(rgba)};")
        entries.append((f"palette.{k}", f"Token::Color(palette::{k.upper()})"))
    module("palette", "Brand palette", lines)

    lines = []
    for k, spec in t["color"].items():
        rgba = resolve(t, k, spec)
        note = f" (macOS: system {spec['system']})" if "system" in spec else ""
        lines.append(f"/// {k}{note}\n    pub const {k.upper()}: Color = {color_const(rgba)};")
        entries.append((f"color.{k}", f"Token::Color(color::{k.upper()})"))
    module("color", "Semantic colours", lines)

    for g in ("opacity",) + LENGTH_GROUPS:
        lines = [f"pub const {k.upper()}: f32 = {num(v)};" for k, v in t[g].items()]
        entries += [(f"{g}.{k}", f"Token::Number({g}::{k.upper()})") for k in t[g]]
        module(g, "Opacities applied to another colour" if g == "opacity" else f"[{g}] in points (logical pixels)",
               lines)

    def font_const(where, s):
        weight = check_weight(where, s["weight"]).capitalize()
        mono = "true" if s.get("design", "default") == "monospaced" else "false"
        return f"FontStyle {{ size: {num(s['size'])}, weight: Weight::{weight}, monospaced: {mono} }}"

    lines = [f'pub const {k.upper()}: &str = "{v}";' for k, v in t["font"].items()]
    entries += [(f"font.{k}", f"Token::Text(font::{k.upper()})") for k in t["font"]]
    for k, s in t["font_style"].items():
        lines.append(f"pub const {k.upper()}: FontStyle = {font_const(f'font_style.{k}', s)};")
        entries.append((f"font_style.{k}", f"Token::Font(font::{k.upper()})"))
    module("font", "Font families and named fonts", lines)

    lines = []
    for k, s in t["text"].items():
        lines.append(f"pub const {k.upper()}: FontStyle = {font_const(f'text.{k}', s)};")
        entries.append((f"text.{k}", f"Token::Font(text::{k.upper()})"))
    module("text", "Text styles (macOS' system text styles)", lines)

    out.append("/// Every token by its path in tokens.toml (`group.name`), for tests and tools\n")
    out.append("pub const ALL: &[(&str, Token)] = &[\n")
    out.extend(f'    ("{path}", {value}),\n' for path, value in entries)
    out.append("];\n")
    return "".join(out)


# --- Nix -------------------------------------------------------------------------------------------------------------

def nix(t):
    """The omaflake look as look data (look.toml, schema look/v1, plan B141): black, high contrast, white text; red and
    cyan – the hero's split – as fine accents: the active window's border, the active workspace, the cursor, matches.
    Neovim and Emacs: Modus Vivendi (black, WCAG AAA) with the accents."""
    c = {}
    for k, spec in t["look"].items():
        if "alpha" in spec or "rgb" in spec:
            raise ValueError(f"look.{k}: give palette or hex, no alpha or rgb")
        r, g, b, _ = resolve(t, k, spec)
        c[k] = f'"#{round(r * 255):02X}{round(g * 255):02X}{round(b * 255):02X}"'
    terminal = lambda keys: "[" + ", ".join(c[k] for k in keys) + "]"
    return "".join([
        "# " + HEADER.format(c="#"),
        "# The omaflake look ([look] in brand/tokens.toml) as look data – omaflake/catalog has it as\n",
        "# looks/omaflake/omaflake/look.toml; the image flake turns it into each program's configuration.\n",
        '"$schema" = "https://omaflake.dev/schema/look/v1.json"\n',
        'author = "omaflake"\n',
        'license = "MIT"\n',
        'title = "omaflake"\n',
        'description = "Black and high contrast with white text; red and cyan only as fine accents."\n',
        'description_de = "Schwarz und kontrastreich mit weißer Schrift; Rot und Cyan nur als feine Akzente."\n',
        'tags = ["dark", "high-contrast"]\n',
        'homepage = "https://omaflake.dev"\n',
        'appearance = "dark"\n\n',
        "[colors]\n",
        f"background = {c['base']}\n",
        f"surface = {c['surface']}\n",
        f"selection = {c['border']}\n",
        f"text = {c['text']}\n",
        f"subtext = {c['subtext']}\n",
        f"muted = {c['muted']}\n",
        f"accent = {c['cyan']}\n",
        f"urgent = {c['red']}\n",
        f"cursor = {c['cyan']}\n\n",
        "[terminal]\n",
        f"normal = {terminal(['overlay', 'red', 'green', 'yellow', 'blue', 'magenta', 'cyan', 'subtext'])}\n",
        f"bright = {terminal(['muted', 'red', 'green', 'yellow', 'blue', 'magenta', 'cyan', 'text'])}\n\n",
        "[desktop]\n",
        f"border = [{c['red']}, {c['cyan']}]   # the active window: the split as a gradient\n",
        f"inactive_border = {c['overlay']}\n",
        f"clock = {c['text']}\n",
        f"split = [{c['red']}, {c['cyan']}]    # the active workspace's number: a 1 px red/cyan edge\n",
        f"prompt = {{ ok = {c['cyan']}, error = {c['red']}, directory = {c['text']} }}\n",
        'gtk = "adw-gtk3-dark"\n',
        'cursor_theme = "Bibata-Modern-Classic"\n\n',
        "[neovim]\n",
        'theme = "modus"\n',
        'style = "modus_vivendi"\n\n',
        "[emacs]\n",
        'theme = "modus"\n',
        'style = "modus-vivendi"\n',
    ])


def main(argv):
    check = "--check" in argv
    t = load()
    stale = []
    for path, content in ((SWIFT, swift(t)), (RUST, rust(t)), (NIX, nix(t))):
        current = open(path).read() if os.path.exists(path) else None
        if current == content:
            continue
        if check:
            stale.append(os.path.relpath(path, ROOT))
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w") as f:
                f.write(content)
            print("wrote", os.path.relpath(path, ROOT))
    if stale:
        print("out of date with brand/tokens.toml (run python3 brand/tokens.py):", ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
