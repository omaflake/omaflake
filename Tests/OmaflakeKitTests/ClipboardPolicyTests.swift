import Darwin
import Foundation
import Testing
@testable import OmaflakeKit

@Suite(.timeLimit(.minutes(1)))
struct ClipboardPolicyTests {
    @Test func ordinaryContentsAreShared() {
        #expect(ClipboardPolicy.shares(types: ["public.utf8-plain-text", "NSStringPboardType"]))
        #expect(ClipboardPolicy.shares(types: ["public.png", "public.tiff"]))
        #expect(ClipboardPolicy.shares(types: []))
    }

    @Test func concealedTransientAndAutoGeneratedContentsStayOnTheHost() {
        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            #expect(!ClipboardPolicy.shares(types: ["public.utf8-plain-text", marker]))
            #expect(!ClipboardPolicy.shares(types: [marker]))
        }
        // Only the exact markers count
        #expect(ClipboardPolicy.shares(types: ["org.nspasteboard.source", "public.utf8-plain-text"]))
    }

    @Test func onlyTextAndPNGAreAcceptedFromAGuest() {
        #expect(ClipboardPolicy.accepts(mime: "text/plain;charset=utf-8"))
        #expect(ClipboardPolicy.accepts(mime: "image/png"))
        for other in ["", "text/plain", "text/html", "image/tiff", "application/octet-stream", "IMAGE/PNG"] {
            #expect(!ClipboardPolicy.accepts(mime: other))
        }
    }

    /// An answer to a control client that has gone is dropped: no signal ends the process, the write loop ends
    @Test func aControlAnswerToAClientThatIsGoneIsDropped() {
        var fds: [Int32] = [0, 0]
        #expect(socketpair(AF_UNIX, SOCK_STREAM, 0, &fds) == 0)
        ControlServer.noSigpipe(fds[0])   // as when the connection is accepted
        close(fds[1])
        ControlServer.write(["state": String(repeating: "x", count: 1 << 20)], to: fds[0])
        close(fds[0])
    }
}
