"""Generates the translation tables of the Rust interfaces (omaf ui, the Linux app) from the macOS app's
Localizable.strings – the source of truth for every language:

    App/Resources/de.lproj/Localizable.strings  →  crates/omaflake-i18n/src/de.rs

Keys are the English texts (docs/api.md §10.2). Needs Python 3, nothing else. Run from anywhere:
    python3 scripts/translations.py            write the tables
    python3 scripts/translations.py --check    fail (exit 1) when a table is out of date
crates/omaflake-i18n/tests/up_to_date.rs checks the same with cargo test.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LANGUAGES = {"de": "German"}


def source(lang):
    return os.path.join(ROOT, "App", "Resources", f"{lang}.lproj", "Localizable.strings")


def target(lang):
    return os.path.join(ROOT, "crates", "omaflake-i18n", "src", f"{lang}.rs")


def parse(text):
    """The pairs of a .strings file ("key" = "value"; with /* */ and // comments); a later key wins."""
    pairs, i, n = {}, 0, len(text)

    def skip(i):
        while i < n:
            if text[i].isspace():
                i += 1
            elif text.startswith("/*", i):
                end = text.find("*/", i + 2)
                if end < 0:
                    raise ValueError("unterminated comment")
                i = end + 2
            elif text.startswith("//", i):
                end = text.find("\n", i)
                i = n if end < 0 else end + 1
            else:
                break
        return i

    def string(i):
        if text[i] != '"':
            raise ValueError(f"expected a string at {text[i:i + 40]!r}")
        out, i = [], i + 1
        while True:
            c = text[i]
            if c == '"':
                return "".join(out), i + 1
            if c == "\\":
                e = text[i + 1]
                if e in "\"\\'":
                    out.append(e)
                    i += 2
                elif e in "ntr":
                    out.append({"n": "\n", "t": "\t", "r": "\r"}[e])
                    i += 2
                elif e in "uU":
                    out.append(chr(int(text[i + 2:i + 6], 16)))
                    i += 6
                else:
                    raise ValueError(f"unknown escape \\{e}")
            else:
                out.append(c)
                i += 1

    while True:
        i = skip(i)
        if i >= n:
            return pairs
        key, i = string(i)
        i = skip(i)
        if text[i] != "=":
            raise ValueError(f"expected = after {key!r}")
        value, i = string(skip(i + 1))
        i = skip(i)
        if text[i] != ";":
            raise ValueError(f"expected ; after {key!r}")
        pairs[key] = value
        i += 1


def literal(s):
    out = []
    for c in s:
        if c in '"\\':
            out.append("\\" + c)
        elif c == "\n":
            out.append("\\n")
        elif c == "\t":
            out.append("\\t")
        elif c == "\r":
            out.append("\\r")
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def rust(lang, pairs):
    name = LANGUAGES[lang]
    rel = os.path.relpath(source(lang), ROOT)
    lines = [
        "// SPDX-License-Identifier: AGPL-3.0-or-later\n",
        f"// Generated by scripts/translations.py from {rel} – do not edit.\n",
        "\n",
        f"/// {name}: (English key, translation), sorted by key (byte order) for a binary search\n",
        "#[rustfmt::skip]\n",
        f"pub static {lang.upper()}: &[(&str, &str)] = &[\n",
    ]
    for key in sorted(pairs, key=lambda k: k.encode()):
        lines.append(f"    ({literal(key)}, {literal(pairs[key])}),\n")
    lines.append("];\n")
    return "".join(lines)


def main(argv):
    check = "--check" in argv
    stale = []
    for lang in LANGUAGES:
        with open(source(lang), encoding="utf-8") as f:
            content = rust(lang, parse(f.read()))
        path = target(lang)
        current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if current == content:
            continue
        if check:
            stale.append(os.path.relpath(path, ROOT))
        else:
            with open(path, "w", encoding="utf-8") as f:
                f.write(content)
            print("wrote", os.path.relpath(path, ROOT))
    if stale:
        print("out of date with Localizable.strings (run python3 scripts/translations.py):", ", ".join(stale),
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
